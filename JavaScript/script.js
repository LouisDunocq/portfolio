// ===== Changement de thème =====

// on récup les bouttons
const boutonTheme = document.querySelector("#bouton-theme"); // l'identifiant
const iconeTheme = boutonTheme.querySelector("i");  // La seconde récupère l'élément <i> qui contient l'icône Font Awesome.

// Appliquer le thème enregistré au chargement de la page
const themeEnregistre = localStorage.getItem("theme");

if (themeEnregistre === "clair") {
    document.body.classList.add("mode-clair");
}

// Mettre à jour l'icône selon le thème actuel
function actualiserIconeTheme() {
    const modeClairActif = document.body.classList.contains("mode-clair");

    if (modeClairActif) {
        iconeTheme.classList.replace("fa-moon", "fa-sun");  // actualise l'icon
        boutonTheme.setAttribute("aria-label", "Activer le mode sombre");
    } else {
        iconeTheme.classList.replace("fa-sun", "fa-moon");
        boutonTheme.setAttribute("aria-label", "Activer le mode clair");
    }
}

// Changer de thème au clic
boutonTheme.addEventListener("click", () => {
    const modeClairActif = document.body.classList.toggle("mode-clair"); // active/désactive mode clair et sombre

    // Enregistrer le choix
    localStorage.setItem("theme", modeClairActif ? "clair" : "sombre");

    // Actualiser l'icône
    actualiserIconeTheme();
});

// Initialiser l'icône au chargement
actualiserIconeTheme();