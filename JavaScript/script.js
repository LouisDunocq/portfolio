 // ===== Système de traduction =====

const boutonLangue = document.querySelector("#bouton-langue");

let langueActuelle = localStorage.getItem("langue") || "fr";

function changerLangue(langue) {
    // Parcourir tous les éléments possédant data-i18n
    document.querySelectorAll("[data-i18n]").forEach((element) => {  // récup tout les éléments html avec cet attribut
        const cle = element.dataset.i18n;  // récup clé de trad
        const traduction = traductions[langue][cle];  // recup le texte correspondant dans la langue choisi

        // Modifier le texte uniquement si la traduction existe
        if (traduction !== undefined) {
            element.textContent = traduction;
        }
    });

    // Mémoriser la langue sélectionnée
    langueActuelle = langue;
    localStorage.setItem("langue", langue);  // enregistre la langue choisi

    // Afficher la langue vers laquelle on peut basculer
    boutonLangue.textContent = langue === "fr" ? "EN" : "FR";

    // Définir la langue du document HTML
    document.documentElement.lang = langue;
}

// Basculer entre le français et l'anglais
boutonLangue.addEventListener("click", () => {
    const nouvelleLangue = langueActuelle === "fr" ? "en" : "fr";
    changerLangue(nouvelleLangue);
});

// Appliquer la langue enregistrée au chargement
changerLangue(langueActuelle);


















 
 
 // ===== Onglets À propos =====

const ongletsProfil = document.querySelectorAll(".profil-onglet");
const panneauxProfil = document.querySelectorAll(".profil-panel");
const imageProfil = document.querySelector(".profil-image");
const sectionProfil = document.querySelector("#a-propos");

ongletsProfil.forEach((onglet) => {
    onglet.addEventListener("click", () => {
        const categorie = onglet.dataset.onglet;

        // Mettre à jour les onglets
        ongletsProfil.forEach((element) => {
            const selectionne = element === onglet;

            element.classList.toggle("actif", selectionne);
            element.setAttribute("aria-selected", selectionne);
            element.tabIndex = selectionne ? 0 : -1;
        });

        // Afficher le bon panneau
        panneauxProfil.forEach((panneau) => {
            sectionProfil.classList.toggle("sans-photo", categorie !== "moi");
            const selectionne =
                panneau.id === `contenu-${categorie}`;

            panneau.hidden = !selectionne;
            panneau.classList.toggle("actif", selectionne);
        });

        // Afficher la photo uniquement dans l'onglet « Moi »
        if (imageProfil) {
            imageProfil.hidden = categorie !== "moi";
        }
    });
});





